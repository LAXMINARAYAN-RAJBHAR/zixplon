// Runs before every build/start. Writes the same build ID to:
//  - public/version.json  (what the server reports)
//  - src/buildInfo.js     (what this bundle was built with)
const fs = require("fs");
const path = require("path");

const sha = (process.env.VERCEL_GIT_COMMIT_SHA || "local").slice(0, 8);
const id = `${sha}-${Date.now()}`;
const root = path.resolve(__dirname, "..");

fs.writeFileSync(
  path.join(root, "public", "version.json"),
  JSON.stringify({ id }) + "\n"
);
fs.writeFileSync(
  path.join(root, "src", "buildInfo.js"),
  `// Auto-generated by scripts/generate-version.cjs. Do not edit.\nexport const BUILD_ID = "${id}";\n`
);

console.log("Build ID:", id);